#!/usr/bin/env node
/*
 * Bundles the JSON data and the engine into docs/js so the site works:
 *   - on GitHub Pages
 *   - when you double-click docs/index.html (no server needed)
 *
 * Run after editing anything in data/ or src/:   node tools/build.js
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const read = f => JSON.parse(fs.readFileSync(path.join(root, 'data', f), 'utf8'));

const traits = read('traits.json');
const courses = read('courses.json');
const questions = read('questions.json');

// light sanity checks so a typo in the JSON fails loudly here, not in a student's browser
const ids = new Set(traits.traits.map(t => t.id));
const problems = [];
courses.courses.forEach(c => {
  Object.keys(c.profile).forEach(k => { if (!ids.has(k)) problems.push(`course ${c.id}: unknown trait "${k}"`); });
  if (!courses.colleges[c.college]) problems.push(`course ${c.id}: unknown college "${c.college}"`);
  if (!Array.isArray(c.strand) || c.strand.length !== 5) problems.push(`course ${c.id}: strand must have 5 numbers`);
});
questions.questions.forEach(q => {
  const effs = q.type === 'statement' ? [q.effects] : (q.options || []).map(o => o.effects);
  if (!effs.length || effs.some(e => !e)) problems.push(`question ${q.id}: missing effects/options`);
  effs.forEach(e => Object.keys(e || {}).forEach(k => { if (!ids.has(k)) problems.push(`question ${q.id}: unknown trait "${k}"`); }));
});
const qids = questions.questions.map(q => q.id);
if (new Set(qids).size !== qids.length) problems.push('duplicate question ids');
if (problems.length) {
  console.error('Data problems:\n - ' + problems.join('\n - '));
  process.exit(1);
}

const bundle = {
  traits: traits.traits,
  courses: courses.courses,
  colleges: courses.colleges,
  campus: courses.meta.campus,
  dataVersion: courses.meta.version,
  questions: questions.questions,
  statementScale: questions.meta.statementScale,
  strandQuestion: questions.strandQuestion
};

const outDir = path.join(root, 'docs', 'js');
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'data.js'),
  '/* Generated by tools/build.js - edit the files in /data, then run the build again. */\n' +
  'window.COURSE_DATA = ' + JSON.stringify(bundle) + ';\n');
fs.copyFileSync(path.join(root, 'src', 'engine.js'), path.join(outDir, 'engine.js'));

console.log(`Built docs/js/data.js: ${bundle.courses.length} programs, ${bundle.questions.length} questions, ${bundle.traits.length} traits.`);
